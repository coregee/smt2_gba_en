REGIONS = [
    (0x02000000, 0x02040000, "EWRAM"),
    (0x03000000, 0x03008000, "IWRAM"),
    (0x05000000, 0x05000400, "PLTT"),
    (0x06000000, 0x06018000, "VRAM"),
    (0x07000000, 0x07000400, "OAM"),
]


def describe(v: int):
    if 0x04000000 <= v < 0x04000400:
        n = IO.get(v - 0x04000000)
        return n or f"IO+0x{v - 0x04000000:X}"
    for lo, hi, n in REGIONS:
        if lo <= v < hi:
            return n if v == lo else f"{n}+0x{v - lo:X}"
    return None
